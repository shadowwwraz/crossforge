import type { CrosshairSpec, Layer, LayerKind } from './types';

let seq = 0;
function L(kind: LayerKind, patch: Partial<Layer> = {}): Layer {
  seq += 1;
  return {
    id: `p${seq}`,
    kind,
    enabled: true,
    length: 8,
    thickness: 2,
    gap: 5,
    radius: 8,
    rotation: 0,
    ...patch,
  };
}

function spec(s: Omit<CrosshairSpec, 'offsetX' | 'offsetY' | 'createdAt' | 'layers'> & { layers: Layer[] }): CrosshairSpec {
  return { offsetX: 0, offsetY: 0, ...s };
}

